"""Generate consumers and strict contract schema from the reviewed source table."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    table = json.loads((ROOT / 'catalog/reality-runtime-fields.json').read_text(encoding='utf8'))
    rows = table['fields']
    assert len({r['field_path'] for r in rows}) == len(rows)
    surfaces = [r['surface'] for r in rows if r['surface'] is not None]
    assert len(set(surfaces)) == len(surfaces)
    for row in rows:
        assert row['status'] in {'APPLIED','PARTIAL','PENDING','DIAGNOSTIC_ONLY','HOST_ONLY','UNSUPPORTED'}
        assert row['reason'] and (row['status'] != 'APPLIED' or row['surface'] and row['runtime_covered'] and row['linked_base_path'] and row['parity_requirement'] == 'EXACT')
        assert row['status'] != 'HOST_ONLY' or row['metadata_only'] and not row['safe_representation']
    legacy = json.loads((ROOT / 'catalog/reality-runtime-fields-v1.json').read_text(encoding='utf8'))
    legacy_literal = json.dumps(json.dumps(legacy, separators=(',', ':'))).replace('$', '\\$')
    literal = json.dumps(json.dumps(table, separators=(',', ':'))).replace('$', '\\$')
    kotlin = '// Generated by tools/generate_runtime_contract.py.\npackage dev.cyclone.cloak.forge\n\ninternal object RealityRuntimeTable {\n    const val json = ' + literal + '\n    const val legacyJson = ' + legacy_literal + '\n}\n'
    variants = []
    for row in rows:
        props = {key: {'const': value} for key, value in row.items()}
        props['present'] = {'type': 'boolean'}
        props['parity_state'] = {'const': 'NOT_REQUIRED'}
        props['parity_passed'] = {'const': None}
        conditions = []
        if row['linked_base_path']:
            props['status'] = {'enum': ['APPLIED','PARTIAL']}
            props['parity_state'] = {'enum': ['MATCHED','MISMATCHED','NOT_PRESENT','BASE_MISSING']}
            props['parity_passed'] = {'type': ['boolean','null']}
            for state in ['MATCHED','MISMATCHED','NOT_PRESENT','BASE_MISSING']:
                conditions.append({'if': {'properties': {'parity_state': {'const': state}}}, 'then': {'properties': {
                    'status': {'const': 'APPLIED' if state == 'MATCHED' else 'PARTIAL'},
                    'present': {'const': state != 'NOT_PRESENT'},
                    'parity_passed': {'const': True if state == 'MATCHED' else False if state == 'MISMATCHED' else None}}}})
        if not conditions: conditions = [True]
        variants.append({'type': 'object', 'additionalProperties': False, 'required': list(props), 'properties': props, 'allOf': conditions})
    schema = {'$schema': 'https://json-schema.org/draft/2020-12/schema', 'title': 'Reality Runtime Contract format 2',
              'type': 'object', 'additionalProperties': False, 'required': ['format', 'schema_version', 'presence', 'fields'],
              'properties': {'format': {'const': 2}, 'schema_version': {'enum': ['0.2', '0.3', '0.4']},
                             'presence': {'enum': ['present', 'not present']},
                             'fields': {'type': 'array', 'maxItems': len(rows), 'items': {'oneOf': variants},
                                        'uniqueItems': True}},
              'allOf': [
                  {'if': {'properties': {'presence': {'const': 'present'}}}, 'then': {'properties': {'schema_version': {'const': '0.4'}, 'fields': {'minItems': len(rows)}}},
                   'else': {'properties': {'fields': {'maxItems': 0}}}},
                  *[{'properties': {'fields': {'contains': {'properties': {'field_path': {'const': row['field_path']}}, 'required': ['field_path']}, 'minContains': 0, 'maxContains': 1}}} for row in rows]],
              '$comment': 'Fixed reviewed capabilities; changing a status requires updating the source table and regenerating consumers.'}
    schema = {'$schema': schema['$schema'], 'oneOf': [schema, json.loads((ROOT / 'schema/reality-runtime.contract.v1.json').read_text(encoding='utf8'))]}
    outputs = {
        'android/app/src/main/java/dev/cyclone/cloak/forge/RealityRuntimeTable.kt': kotlin,
        'android/probe/src/main/assets/reality-runtime-fields.json': json.dumps(table, indent=2) + '\n',
        'schema/reality-runtime.contract.json': json.dumps(schema, indent=2) + '\n',
    }
    sys.path.insert(0, str(ROOT / 'forge'))
    from cloak_forge.runtime_contract import generate_contract
    profile = json.loads((ROOT / 'forge/tests/vectors/reality.json').read_text(encoding='utf8'))['profile']
    outputs['forge/tests/vectors/reality-runtime-contract.json'] = json.dumps(generate_contract(profile), indent=2) + '\n'
    for path, text in outputs.items():
        target = ROOT / path
        if '--check' in sys.argv:
            assert target.read_text(encoding='utf8') == text, 'Regenerate ' + path
        else:
            target.write_text(text, encoding='utf8')


if __name__ == '__main__':
    generate()
