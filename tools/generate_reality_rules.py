"""Generate the pure Kotlin validator's embedded rules from the authoritative JSON schema."""
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'forge'))
from cloak_forge.reality import RULES, MESSAGES, LINKS

def literal(value): return json.dumps(json.dumps(value, separators=(',', ':'), ensure_ascii=True)).replace('$', '\\$')

text = ('// Generated by tools/generate_reality_rules.py; do not edit.\n'
        'package dev.cyclone.cloak.forge\n\nimport org.json.JSONObject\n\ninternal object RealityRules {\n'
        f'    const val json = {literal(RULES)}\n'
        f'    val messages get() = JSONObject({literal(MESSAGES)})\n'
        f'    val links get() = JSONObject({literal(LINKS)})\n' + '}\n')
target = ROOT / 'android/app/src/main/java/dev/cyclone/cloak/forge/RealityRules.kt'
if '--check' in sys.argv:
    assert target.read_text(encoding='utf8') == text, 'Regenerate embedded Reality rules.'
else:
    target.write_text(text, encoding='utf8')
